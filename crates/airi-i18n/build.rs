//! Build script for airi-i18n: parses locale YAML files and generates a static lookup table.

use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use walkdir::WalkDir;

fn main() -> Result<()> {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=../../packages/i18n/src/locales");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    // crates/airi-i18n -> repo root
    let repo_locales = manifest_dir.join("../../packages/i18n/src/locales");
    let locales_root = if repo_locales.exists() {
        repo_locales
    } else {
        let alt = Path::new("../../packages/i18n/src/locales");
        if alt.exists() {
            alt.to_path_buf()
        } else {
            generate_empty()?;
            return Ok(());
        }
    };

    generate(&locales_root)
}

fn generate(locales_root: &Path) -> Result<()> {
    let mut locale_data: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();

    for entry in WalkDir::new(locales_root)
        .into_iter()
        .filter_map(Result::ok)
    {
        let path = entry.path();
        let ext = path.extension().and_then(|s| s.to_str());
        if ext != Some("yaml") && ext != Some("yml") {
            continue;
        }

        let rel_path = path.strip_prefix(locales_root).unwrap_or(path);
        let mut comps = rel_path.components();
        let Some(locale_comp) = comps.next() else {
            continue;
        };
        let locale = locale_comp.as_os_str().to_string_lossy().to_string();
        // Skip non-locale dirs/files like index.ts at root
        if locale == "index.ts" {
            continue;
        }

        let mut prefix = String::new();
        // Build prefix from the path after the locale directory: e.g. "tamagotchi/settings.yaml" -> "tamagotchi.settings"
        for c in comps {
            if let std::path::Component::Normal(os) = c {
                if os == "index" {
                    continue;
                }
                let s = os.to_string_lossy();
                if !prefix.is_empty() {
                    prefix.push('.');
                }
                prefix.push_str(s.trim_end_matches(".yaml").trim_end_matches(".yml"));
            }
        }

        let content = fs::read_to_string(path)
            .with_context(|| format!("Failed to read {}", path.display()))?;
        let yaml: serde_yaml::Value = serde_yaml::from_str(&content)
            .with_context(|| format!("Failed to parse YAML {}", path.display()))?;

        let map = locale_data.entry(locale).or_default();
        flatten_yaml(&yaml, prefix, map);
    }

    let all_keys: Vec<String> = locale_data
        .get("en")
        .map(|m| m.keys().cloned().collect())
        .unwrap_or_default();

    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    let out_file = out_dir.join("locale_data.rs");

    let mut code = String::new();
    code.push_str("// Generated by airi-i18n build.rs\n");
    code.push_str("// DO NOT EDIT\n\n");
    code.push_str("use phf::phf_map;\n\n");
    code.push_str("/// Embedded locale data: locale -> dotted key -> message.\n");
    code.push_str("pub static LOCALE_DATA: phf::Map<&'static str, phf::Map<&'static str, &'static str>> = phf_map! {\n");

    for (locale, map) in &locale_data {
        code.push_str(&format!("    {:?} => phf_map! {{\n", locale));
        for (key, value) in map {
            code.push_str(&format!("        {:?} => {:?},\n", key, value));
        }
        code.push_str("    },\n");
    }

    code.push_str("};\n\n");
    code.push_str("/// All dotted keys from the English reference locale.\n");
    code.push_str("pub static ALL_KEYS: &[&str] = &[\n");
    for key in &all_keys {
        code.push_str(&format!("    {:?},\n", key));
    }
    code.push_str("];\n");

    fs::write(&out_file, code)
        .with_context(|| format!("Failed to write {}", out_file.display()))?;

    println!("cargo:rustc-env=I18N_LOCALE_COUNT={}", locale_data.len());
    println!("cargo:rustc-env=I18N_KEY_COUNT={}", all_keys.len());

    Ok(())
}

fn flatten_yaml(value: &serde_yaml::Value, prefix: String, map: &mut BTreeMap<String, String>) {
    match value {
        serde_yaml::Value::Mapping(m) => {
            for (k, v) in m {
                let key_str = match k {
                    serde_yaml::Value::String(s) => s.clone(),
                    serde_yaml::Value::Number(n) => n.to_string(),
                    serde_yaml::Value::Bool(b) => b.to_string(),
                    _ => continue,
                };
                let new_prefix = if prefix.is_empty() {
                    key_str
                } else {
                    format!("{}.{}", prefix, key_str)
                };
                flatten_yaml(v, new_prefix, map);
            }
        }
        serde_yaml::Value::Sequence(seq) => {
            for (i, v) in seq.iter().enumerate() {
                let new_prefix = if prefix.is_empty() {
                    i.to_string()
                } else {
                    format!("{}.{}", prefix, i)
                };
                flatten_yaml(v, new_prefix, map);
            }
        }
        serde_yaml::Value::String(s) => {
            if !prefix.is_empty() {
                map.insert(prefix, s.clone());
            }
        }
        serde_yaml::Value::Number(n) => {
            if !prefix.is_empty() {
                map.insert(prefix, n.to_string());
            }
        }
        serde_yaml::Value::Bool(b) => {
            if !prefix.is_empty() {
                map.insert(prefix, b.to_string());
            }
        }
        serde_yaml::Value::Null => {
            if !prefix.is_empty() {
                map.insert(prefix, String::new());
            }
        }
        serde_yaml::Value::Tagged(t) => {
            flatten_yaml(&t.value, prefix, map);
        }
    }
}

fn generate_empty() -> Result<()> {
    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    let out_file = out_dir.join("locale_data.rs");
    let code = r#"// Generated by airi-i18n build.rs (empty fallback)
// DO NOT EDIT

use phf::phf_map;

/// Embedded locale data: locale -> dotted key -> message.
pub static LOCALE_DATA: phf::Map<&'static str, phf::Map<&'static str, &'static str>> = phf_map! {
    "en" => phf_map! {},
};

/// All dotted keys from the English reference locale.
pub static ALL_KEYS: &[&str] = &[];
"#;
    fs::write(&out_file, code)?;
    println!("cargo:rustc-env=I18N_LOCALE_COUNT=1");
    println!("cargo:rustc-env=I18N_KEY_COUNT=0");
    Ok(())
}
